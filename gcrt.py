"""Conservative mark-sweep allocator + GC for the hosted IR->x64 backend.

Layout: every block has a 16-byte header [size][state]; payload follows.
state: 0 live-or-garbage, 1 marked, 2 free, 3 pinned (unsafe x_alloc).
Blocks tile each 16MB mmap arena; a start bitmap (1 bit / 16 bytes) lets
the marker turn any interior word into its block. The collector runs only
at safe points (x_gc is called by IR function entry / loop headers when
gc_pend_ is set); roots are the stack, the data segment and pinned
blocks. interp.py stays the semantic reference; this is only the
allocator behind x_malloc.
"""

ARENA = 16 * 1024 * 1024
MAXARENAS = 1024
LIMIT_MIN = 8 * 1024 * 1024
NCLASS = 34  # free[2..32] exact 16-byte classes up to 512, free[33] large


def gc_data(a):
    """Data qwords for the collector; emitted after gc_data_hi."""
    for nm, v in (("gc_tab_", 0), ("gc_n_", 0), ("gc_lo_", 0), ("gc_hi_", 0),
                  ("gc_alloc_", 0), ("gc_cbase_", 0), ("gc_cbm_", 0), ("gc_limit_", LIMIT_MIN),
                  ("gc_pend_", 0), ("gc_stk_", 0)):
        a.data_label(nm)
        a.data_qword(v)
    a.data_label("gc_free_")
    for _ in range(NCLASS):
        a.data_qword(0)


def emit_gc_malloc(g):
    a = g.a
    T = g.new_tmp
    ld = a.mov_rm_rip
    st = a.mov_mr_rip

    def mmap_rsi():
        # rsi = length -> rax = address (exit 99 on failure)
        a.mov_ri32("rdi", 0)
        a.mov_ri32("rdx", 3)
        a.mov_ri32("r10", 0x22)
        a.mov_ri32("r8", -1)
        a.mov_ri32("r9", 0)
        a.mov_ri32("rax", 9)
        a.syscall()
        a.test_rr("rax", "rax")
        ok = T("gm")
        a.jcc("ns", ok)
        a.mov_ri32("rdi", 99)
        a.mov_ri32("rax", 60)
        a.syscall()
        a.label(ok)

    # ---------------- x_malloc: rdi = bytes -> rax = payload ----------------
    # Callers rely on rdi and r8-r11 surviving (the old allocator's fast
    # path only touched rax/rcx/rdx/rsi), so the slow paths are wrapped.
    a.label("x_malloc")
    a.mov_rr("rax", "rdi")
    a.add_ri32("rax", 31)
    a.and_ri32("rax", -16)          # block size incl. 16B header
    L1 = T("gm")
    a.cmp_ri32("rax", 32)
    a.jcc("ae", L1)
    a.mov_ri32("rax", 32)
    a.label(L1)
    ld("rcx", "gc_alloc_")
    a.add_rr("rcx", "rax")
    st("gc_alloc_", "rcx")
    ld("rdx", "gc_limit_")
    Lnp = T("gm")
    a.cmp_rr("rcx", "rdx")
    a.jcc("b", Lnp)
    a.mov_ri32("rdx", 1)
    st("gc_pend_", "rdx")
    a.label(Lnp)
    Llarge, Lbump, Lreuse, Lnew = T("gl"), T("gb"), T("gr"), T("gn")
    Lslow, Lx_in = T("gs"), T("gi")
    Lfr = T("gf")
    a.cmp_ri32("rax", 512)
    a.jcc("a", Lslow)
    a.mov_rr("rcx", "rax")
    a.shr_ri8("rcx", 4)
    a.lea_rip("rdx", "gc_free_")
    a.mov_rmx("rsi", "rdx", "rcx", 8, 0)
    a.test_rr("rsi", "rsi")
    Lfb = T("gf")
    a.jcc("e", Lfb)
    a.mov_rm("rax", "rsi", 16)
    a.mov_mrx("rdx", "rcx", 8, 0, "rax")   # pop the class list
    a.mov_rm("rcx", "rsi", 0)
    a.mov_ri32("rdx", 0)
    a.mov_mr("rsi", "rdx", 8)               # state = 0
    a.lea_m("rax", "rsi", 16)
    a.shr_ri8("rcx", 3)
    a.sub_ri32("rcx", 2)                    # payload qwords
    a.label(Lfr)
    a.mov_mr("rax", "rdx", 0)
    a.add_ri32("rax", 8)
    a.sub_ri32("rcx", 1)
    a.jcc("ne", Lfr)
    a.lea_m("rax", "rsi", 16)
    a.ret()
    a.label(Lfb)                            # class list empty: bump fast path
    a.mov_rr("rax", "rdi")
    a.add_ri32("rax", 31)
    a.and_ri32("rax", -16)
    Lmin = T("gm")
    a.cmp_ri32("rax", 32)
    a.jcc("ae", Lmin)
    a.mov_ri32("rax", 32)
    a.label(Lmin)
    ld("rcx", "bump_ptr_")
    a.test_rr("rcx", "rcx")
    a.jcc("e", Lslow)
    ld("rdx", "bump_end_")
    a.lea_m("rsi", "rcx", 0, "rax", 1)
    a.cmp_rr("rsi", "rdx")
    a.jcc("a", Lslow)
    st("bump_ptr_", "rsi")
    a.mov_mr("rcx", "rax", 0)
    ld("rdx", "gc_cbase_")
    a.mov_rr("rsi", "rcx")
    a.sub_rr("rsi", "rdx")
    a.shr_ri8("rsi", 4)
    a.mov_rr("rax", "rsi")
    a.shr_ri8("rax", 6)
    a.shl_ri8("rax", 3)
    ld("rdx", "gc_cbm_")
    a.add_rr("rax", "rdx")
    a.push_r("rcx")
    a.mov_rr("rcx", "rsi")
    a.and_ri32("rcx", 63)
    a.mov_ri32("rdx", 1)
    a.shl_cl("rdx")
    a.pop_r("rcx")
    a.mov_rm("rsi", "rax", 0)
    a.or_rr("rsi", "rdx")
    a.mov_mr("rax", "rsi", 0)
    a.lea_m("rax", "rcx", 16)
    a.ret()
    a.label(Lslow)                          # everything else: wrapped
    for r in ("rdi", "r8", "r9", "r10", "r11"):
        a.push_r(r)
    a.call("x_malloc_in")
    for r in ("r11", "r10", "r9", "r8", "rdi"):
        a.pop_r(r)
    a.ret()
    a.label("x_malloc_in")
    a.mov_rr("rax", "rdi")
    a.add_ri32("rax", 31)
    a.and_ri32("rax", -16)
    Lmin2 = T("gm")
    a.cmp_ri32("rax", 32)
    a.jcc("ae", Lmin2)
    a.mov_ri32("rax", 32)
    a.label(Lmin2)
    a.label(Llarge)                 # first-fit on the large list
    a.lea_rip("rdx", "gc_free_")
    a.add_ri32("rdx", 8 * 33)
    Lloop, Lfound = T("gf"), T("gf")
    a.label(Lloop)
    a.mov_rm("rsi", "rdx", 0)
    a.test_rr("rsi", "rsi")
    a.jcc("e", Lbump)
    a.mov_rm("rcx", "rsi", 0)
    a.cmp_rr("rcx", "rax")
    a.jcc("ae", Lfound)
    a.lea_m("rdx", "rsi", 16)
    a.jmp(Lloop)
    a.label(Lfound)
    a.mov_rm("rdi", "rsi", 16)
    a.mov_mr("rdx", "rdi", 0)       # unlink
    a.sub_rr("rcx", "rax")          # remainder
    a.cmp_ri32("rcx", 32)
    a.jcc("b", Lreuse)
    a.mov_rr("rdi", "rsi")
    a.add_rr("rdi", "rax")          # remainder block
    a.mov_mr("rdi", "rcx", 0)
    a.mov_mr("rsi", "rax", 0)
    a.mov_ri32("rdx", 2)
    a.mov_mr("rdi", "rdx", 8)
    a.push_r("rsi")
    a.push_r("rdi")
    a.push_r("rcx")
    a.mov_ri32("rsi", 1)
    a.call("x_gc_bit")              # rdi = remainder start
    a.pop_r("rcx")
    a.pop_r("rdi")
    a.call("x_gc_finsert")
    a.pop_r("rsi")
    a.label(Lreuse)                 # rsi = block: clear state, zero payload
    a.mov_rm("rcx", "rsi", 0)
    a.mov_ri32("rdx", 0)
    a.mov_mr("rsi", "rdx", 8)
    a.lea_m("rax", "rsi", 16)
    a.lea_m("rdi", "rsi", 0, "rcx", 1)
    a.mov_rr("r8", "rax")
    Lz = T("gz")
    a.label(Lz)
    a.mov_mr("r8", "rdx", 0)
    a.add_ri32("r8", 8)
    a.cmp_rr("r8", "rdi")
    a.jcc("b", Lz)
    a.ret()
    a.label(Lbump)                  # rax = block size
    ld("rcx", "bump_ptr_")
    a.test_rr("rcx", "rcx")
    a.jcc("e", Lnew)
    ld("rdx", "bump_end_")
    a.lea_m("rsi", "rcx", 0, "rax", 1)
    a.cmp_rr("rsi", "rdx")
    a.jcc("a", Lnew)
    st("bump_ptr_", "rsi")
    a.mov_mr("rcx", "rax", 0)
    a.mov_rr("rdi", "rcx")          # set the start bit (current arena)
    ld("r8", "gc_cbase_")
    a.mov_rr("rdx", "rdi")
    a.sub_rr("rdx", "r8")
    a.shr_ri8("rdx", 4)
    a.mov_rr("rsi", "rdx")
    a.shr_ri8("rsi", 6)
    a.shl_ri8("rsi", 3)
    ld("r8", "gc_cbm_")
    a.add_rr("rsi", "r8")
    a.mov_rr("rcx", "rdx")
    a.and_ri32("rcx", 63)
    a.mov_ri32("rdx", 1)
    a.shl_cl("rdx")
    a.mov_rm("r8", "rsi", 0)
    a.or_rr("r8", "rdx")
    a.mov_mr("rsi", "r8", 0)
    a.lea_m("rax", "rdi", 16)
    a.ret()
    a.label(Lnew)                   # new arena; rax = block size
    a.push_r("rax")
    a.mov_rr("rsi", "rax")
    a.add_ri32("rsi", 4095)
    a.and_ri32("rsi", -4096)
    Lg = T("gn")
    a.cmp_ri32("rsi", ARENA)
    a.jcc("ae", Lg)
    a.mov_ri32("rsi", ARENA)
    a.label(Lg)
    a.push_r("rsi")                 # len
    Lt = T("gn")
    ld("rdx", "gc_tab_")
    a.test_rr("rdx", "rdx")
    a.jcc("ne", Lt)
    a.mov_ri32("rsi", 32 * MAXARENAS)
    mmap_rsi()
    st("gc_tab_", "rax")
    a.label(Lt)
    ld("rax", "gc_n_")
    Ln = T("gn")
    a.cmp_ri32("rax", MAXARENAS)
    a.jcc("b", Ln)
    a.mov_ri32("rdi", 99)
    a.mov_ri32("rax", 60)
    a.syscall()
    a.label(Ln)
    Lp2 = T("gn")
    a.test_rr("rax", "rax")
    a.jcc("e", Lp2)
    ld("rcx", "bump_ptr_")
    a.mov_rr("rdx", "rax")
    a.sub_ri32("rdx", 1)
    a.shl_ri8("rdx", 5)
    ld("rsi", "gc_tab_")
    a.add_rr("rdx", "rsi")
    a.mov_mr("rdx", "rcx", 24)      # previous arena: used = bump_ptr_
    a.label(Lp2)
    a.mov_rm("rsi", "rsp", 0)
    mmap_rsi()
    a.push_r("rax")                 # base
    a.mov_rm("rsi", "rsp", 8)
    a.shr_ri8("rsi", 7)
    a.add_ri32("rsi", 4095)
    a.and_ri32("rsi", -4096)
    mmap_rsi()                      # bitmap
    ld("rcx", "gc_n_")
    a.mov_rr("rdx", "rcx")
    a.shl_ri8("rdx", 5)
    ld("rsi", "gc_tab_")
    a.add_rr("rdx", "rsi")
    a.pop_r("rdi")                  # base
    a.pop_r("rsi")                  # len
    a.mov_mr("rdx", "rdi", 0)
    a.add_rr("rsi", "rdi")          # end
    a.mov_mr("rdx", "rsi", 8)
    a.mov_mr("rdx", "rax", 16)
    a.mov_mr("rdx", "rdi", 24)
    a.add_ri32("rcx", 1)
    st("gc_n_", "rcx")
    st("bump_ptr_", "rdi")
    st("bump_end_", "rsi")
    st("gc_cbase_", "rdi")
    st("gc_cbm_", "rax")
    ld("rax", "gc_lo_")
    Lsl, Lnl = T("gn"), T("gn")
    a.test_rr("rax", "rax")
    a.jcc("e", Lsl)
    a.cmp_rr("rdi", "rax")
    a.jcc("ae", Lnl)
    a.label(Lsl)
    st("gc_lo_", "rdi")
    a.label(Lnl)
    ld("rax", "gc_hi_")
    Lnh = T("gn")
    a.cmp_rr("rsi", "rax")
    a.jcc("be", Lnh)
    st("gc_hi_", "rsi")
    a.label(Lnh)
    a.pop_r("rax")                  # block size
    a.jmp(Lbump)

    # x_gc_finsert: rdi = free block, rcx = size (>=32) -> push on its list
    a.label("x_gc_finsert")
    a.mov_rr("rax", "rcx")
    Ls, Lgg = T("fi"), T("fi")
    a.cmp_ri32("rax", 512)
    a.jcc("be", Ls)
    a.mov_ri32("rax", 33)
    a.jmp(Lgg)
    a.label(Ls)
    a.shr_ri8("rax", 4)
    a.label(Lgg)
    a.shl_ri8("rax", 3)
    a.lea_rip("rdx", "gc_free_")
    a.add_rr("rdx", "rax")
    a.mov_rm("rax", "rdx", 0)
    a.mov_mr("rdi", "rax", 16)
    a.mov_mr("rdx", "rdi", 0)
    a.ret()

    # x_gc_bit: rdi = block address, rsi = 1 set / 0 clear start bit
    a.label("x_gc_bit")
    ld("r8", "gc_tab_")
    ld("r9", "gc_n_")
    Lb, Lbf, Lw, Lc = T("gb"), T("gb"), T("gb"), T("gb")
    a.label(Lb)
    a.test_rr("r9", "r9")
    a.jcc("e", Lbf)
    a.sub_ri32("r9", 1)
    a.mov_rr("r10", "r9")
    a.shl_ri8("r10", 5)
    a.add_rr("r10", "r8")
    a.mov_rm("r11", "r10", 0)
    a.cmp_rr("rdi", "r11")
    a.jcc("b", Lb)
    a.mov_rm("rdx", "r10", 8)
    a.cmp_rr("rdi", "rdx")
    a.jcc("ae", Lb)
    a.sub_rr("rdi", "r11")
    a.shr_ri8("rdi", 4)
    a.mov_rr("rcx", "rdi")
    a.and_ri32("rcx", 63)
    a.shr_ri8("rdi", 6)
    a.shl_ri8("rdi", 3)
    a.mov_rm("r11", "r10", 16)
    a.add_rr("rdi", "r11")
    a.mov_ri32("rax", 1)
    a.shl_cl("rax")
    a.mov_rm("rdx", "rdi", 0)
    a.test_rr("rsi", "rsi")
    a.jcc("e", Lc)
    a.or_rr("rdx", "rax")
    a.jmp(Lw)
    a.label(Lc)
    a.not_r("rax")
    a.and_rr("rdx", "rax")
    a.label(Lw)
    a.mov_mr("rdi", "rdx", 0)
    a.label(Lbf)
    a.ret()

    # ---------------- x_gc ----------------
    regs = ["rax", "rcx", "rdx", "rbx", "rbp", "rsi", "rdi", "r8", "r9",
            "r10", "r11", "r12", "r13", "r14", "r15"]
    a.label("x_gc")
    for r in regs:
        a.push_r(r)
    ld("rbx", "gc_tab_")
    ld("r15", "gc_n_")
    Lout = T("gc")
    a.test_rr("r15", "r15")
    a.jcc("e", Lout)
    ld("rcx", "bump_ptr_")
    a.mov_rr("rdx", "r15")
    a.sub_ri32("rdx", 1)
    a.shl_ri8("rdx", 5)
    a.add_rr("rdx", "rbx")
    a.mov_mr("rdx", "rcx", 24)
    ld("r13", "gc_lo_")
    ld("r14", "gc_hi_")
    # mark stack: (total used / 32 + 16) entries of 8 bytes
    a.mov_ri32("r8", 0)
    a.mov_ri32("r9", 0)
    Lu, Lud = T("gc"), T("gc")
    a.label(Lu)
    a.cmp_rr("r9", "r15")
    a.jcc("ae", Lud)
    a.mov_rr("rdx", "r9")
    a.shl_ri8("rdx", 5)
    a.add_rr("rdx", "rbx")
    a.mov_rm("rax", "rdx", 24)
    a.mov_rm("rcx", "rdx", 0)
    a.sub_rr("rax", "rcx")
    a.add_rr("r8", "rax")
    a.add_ri32("r9", 1)
    a.jmp(Lu)
    a.label(Lud)
    a.mov_rr("rsi", "r8")
    a.shr_ri8("rsi", 2)
    a.add_ri32("rsi", 4096 + 4095)
    a.and_ri32("rsi", -4096)
    a.push_r("rsi")                 # len for munmap
    mmap_rsi()
    a.push_r("rax")                 # base for munmap
    a.mov_rr("rbp", "rax")
    a.mov_rr("r12", "rax")
    # roots: stack, data segment, pinned blocks
    a.mov_rr("rsi", "rsp")
    ld("rdx", "gc_stk_")
    a.call("x_gc_scan")
    a.lea_rip("rsi", "gc_data_lo")
    a.lea_rip("rdx", "gc_data_hi")
    a.call("x_gc_scan")
    a.mov_ri32("r9", 0)
    Lpa, Lpb, Lpc, Lpd = T("gp"), T("gp"), T("gp"), T("gp")
    a.label(Lpa)
    a.cmp_rr("r9", "r15")
    a.jcc("ae", Lpd)
    a.mov_rr("rdx", "r9")
    a.shl_ri8("rdx", 5)
    a.add_rr("rdx", "rbx")
    a.mov_rm("rsi", "rdx", 0)
    a.mov_rm("r10", "rdx", 24)
    a.add_ri32("r9", 1)
    a.label(Lpb)
    a.cmp_rr("rsi", "r10")
    a.jcc("ae", Lpa)
    a.mov_rm("rax", "rsi", 0)
    a.mov_rm("rdx", "rsi", 8)
    a.cmp_ri32("rdx", 3)
    a.jcc("ne", Lpc)
    a.mov_mr("r12", "rsi", 0)
    a.add_ri32("r12", 8)
    a.label(Lpc)
    a.add_rr("rsi", "rax")
    a.jmp(Lpb)
    a.label(Lpd)
    Ld, Ldd = T("gd"), T("gd")
    a.label(Ld)                     # drain the mark stack
    a.cmp_rr("r12", "rbp")
    a.jcc("e", Ldd)
    a.sub_ri32("r12", 8)
    a.mov_rm("rax", "r12", 0)
    a.mov_rm("rdx", "rax", 0)
    a.add_rr("rdx", "rax")
    a.lea_m("rsi", "rax", 16)
    a.call("x_gc_scan")
    a.jmp(Ld)
    a.label(Ldd)
    # sweep
    a.mov_ri32("r12", 0)            # live bytes
    a.lea_rip("rsi", "gc_free_")
    a.mov_ri32("rcx", NCLASS)
    a.mov_ri32("rdx", 0)
    Lfz = T("gs")
    a.label(Lfz)
    a.mov_mr("rsi", "rdx", 0)
    a.add_ri32("rsi", 8)
    a.sub_ri32("rcx", 1)
    a.jcc("ne", Lfz)
    a.mov_ri32("r13", 0)
    Lsa, Lsb, Lsc, Lfree, Lrun, Lend, Lsd = (T("gs") for _ in range(7))
    a.label(Lsa)
    a.cmp_rr("r13", "r15")
    a.jcc("ae", Lsd)
    a.mov_rr("r8", "r13")
    a.shl_ri8("r8", 5)
    a.add_rr("r8", "rbx")
    a.mov_rm("r9", "r8", 0)
    a.mov_rm("r10", "r8", 24)
    a.mov_rm("r11", "r8", 16)
    a.mov_rr("rsi", "r9")
    a.add_ri32("r13", 1)
    a.label(Lsb)
    a.cmp_rr("rsi", "r10")
    a.jcc("ae", Lsa)
    a.mov_rm("rax", "rsi", 0)
    a.mov_rm("rdx", "rsi", 8)
    a.cmp_ri32("rdx", 1)
    a.jcc("ne", Lsc)
    a.mov_ri32("rdx", 0)
    a.mov_mr("rsi", "rdx", 8)
    a.add_rr("r12", "rax")
    a.add_rr("rsi", "rax")
    a.jmp(Lsb)
    a.label(Lsc)
    a.cmp_ri32("rdx", 3)
    a.jcc("ne", Lfree)
    a.add_rr("r12", "rax")
    a.add_rr("rsi", "rax")
    a.jmp(Lsb)
    a.label(Lfree)                  # coalesce a run of free/garbage blocks
    a.mov_rr("rdi", "rsi")
    a.mov_rr("r14", "rax")
    a.add_rr("rsi", "rax")
    a.label(Lrun)
    a.cmp_rr("rsi", "r10")
    a.jcc("ae", Lend)
    a.mov_rm("rdx", "rsi", 8)
    a.cmp_ri32("rdx", 1)
    a.jcc("e", Lend)
    a.cmp_ri32("rdx", 3)
    a.jcc("e", Lend)
    a.mov_rm("rax", "rsi", 0)
    a.mov_rr("rdx", "rsi")          # clear the absorbed block's start bit
    a.sub_rr("rdx", "r9")
    a.shr_ri8("rdx", 4)
    a.mov_rr("rcx", "rdx")
    a.and_ri32("rcx", 63)
    a.shr_ri8("rdx", 6)
    a.shl_ri8("rdx", 3)
    a.add_rr("rdx", "r11")
    a.mov_ri32("rbp", 1)
    a.shl_cl("rbp")
    a.not_r("rbp")
    a.mov_rm("rcx", "rdx", 0)
    a.and_rr("rcx", "rbp")
    a.mov_mr("rdx", "rcx", 0)
    a.add_rr("r14", "rax")
    a.add_rr("rsi", "rax")
    a.jmp(Lrun)
    a.label(Lend)
    a.mov_ri32("rdx", 2)
    a.mov_mr("rdi", "rdx", 8)
    a.mov_mr("rdi", "r14", 0)
    a.mov_rr("rcx", "r14")
    a.push_r("rsi")
    a.call("x_gc_finsert")
    a.pop_r("rsi")
    a.jmp(Lsb)
    a.label(Lsd)
    # next trigger: max(2*live, 8MB) of fresh allocation
    a.mov_rr("rax", "r12")
    a.add_rr("rax", "r12")          # 2x live: amortised O(1) per byte
    Lkeep = T("gs")
    a.cmp_ri32("rax", LIMIT_MIN)
    a.jcc("ae", Lkeep)
    a.mov_ri32("rax", LIMIT_MIN)
    a.label(Lkeep)
    st("gc_limit_", "rax")
    a.mov_ri32("rax", 0)
    st("gc_alloc_", "rax")
    st("gc_pend_", "rax")
    a.pop_r("rdi")                  # munmap the mark stack
    a.pop_r("rsi")
    a.mov_ri32("rax", 11)
    a.syscall()
    a.label(Lout)
    for r in reversed(regs):
        a.pop_r(r)
    a.ret()

    # x_gc_scan: rsi = start, rdx = end; marks every aligned word
    a.label("x_gc_scan")
    Lsl2, Lsx = T("gx"), T("gx")
    a.label(Lsl2)
    a.cmp_rr("rsi", "rdx")
    a.jcc("ae", Lsx)
    a.mov_rm("rdi", "rsi", 0)
    a.call("x_gc_mark1")
    a.add_ri32("rsi", 8)
    a.jmp(Lsl2)
    a.label(Lsx)
    a.ret()

    # x_gc_mark1: rdi = candidate word; preserves rsi, rdx
    a.label("x_gc_mark1")
    Mret = T("gm")
    a.cmp_rr("rdi", "r13")
    a.jcc("b", Mret)
    a.cmp_rr("rdi", "r14")
    a.jcc("ae", Mret)
    a.push_r("rsi")
    a.push_r("rdx")
    Mx, M1, M2, M3 = T("gm"), T("gm"), T("gm"), T("gm")
    a.mov_rr("rcx", "r15")
    a.label(M1)
    a.test_rr("rcx", "rcx")
    a.jcc("e", Mx)
    a.sub_ri32("rcx", 1)
    a.mov_rr("rdx", "rcx")
    a.shl_ri8("rdx", 5)
    a.add_rr("rdx", "rbx")
    a.mov_rm("rsi", "rdx", 0)
    a.cmp_rr("rdi", "rsi")
    a.jcc("b", M1)
    a.mov_rm("r8", "rdx", 24)
    a.cmp_rr("rdi", "r8")
    a.jcc("ae", M1)
    a.mov_rm("r9", "rdx", 16)
    a.mov_rr("r10", "rdi")
    a.sub_rr("r10", "rsi")
    a.shr_ri8("r10", 4)
    a.mov_rr("r11", "r10")
    a.shr_ri8("r11", 6)
    a.mov_rr("rcx", "r10")
    a.and_ri32("rcx", 63)
    a.mov_ri32("rax", 2)
    a.shl_cl("rax")
    a.sub_ri32("rax", 1)
    a.mov_rmx("rdx", "r9", "r11", 8, 0)
    a.and_rr("rdx", "rax")
    a.label(M2)
    a.test_rr("rdx", "rdx")
    a.jcc("ne", M3)
    a.test_rr("r11", "r11")
    a.jcc("e", Mx)
    a.sub_ri32("r11", 1)
    a.mov_rmx("rdx", "r9", "r11", 8, 0)
    a.jmp(M2)
    a.label(M3)                     # rcx = index of highest set bit of rdx
    a.bsr_rr("rcx", "rdx")
    a.mov_rr("rax", "r11")
    a.shl_ri8("rax", 6)
    a.add_rr("rax", "rcx")
    a.shl_ri8("rax", 4)
    a.add_rr("rax", "rsi")          # candidate block start
    a.mov_rm("rdx", "rax", 0)
    a.add_rr("rdx", "rax")
    a.cmp_rr("rdi", "rdx")
    a.jcc("ae", Mx)
    a.lea_m("rcx", "rax", 16)
    a.cmp_rr("rdi", "rcx")
    a.jcc("b", Mx)
    a.mov_rm("rdx", "rax", 8)
    a.test_rr("rdx", "rdx")
    a.jcc("ne", Mx)
    a.mov_ri32("rdx", 1)
    a.mov_mr("rax", "rdx", 8)
    a.mov_mr("r12", "rax", 0)
    a.add_ri32("r12", 8)
    a.label(Mx)
    a.pop_r("rdx")
    a.pop_r("rsi")
    a.label(Mret)
    a.ret()

