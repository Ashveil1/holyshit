#!/usr/bin/env python3
"""Moved native bundle operates with no checkout reference or Python/gcc PATH."""
from pathlib import Path
import json,os,shutil,subprocess,sys,tempfile,time
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
import fmt,interp as reference_interp
passed=failed=0
def check(ok,label):
    global passed,failed
    passed+=int(ok);failed+=int(not ok)
    print(('ok  ' if ok else 'FAIL'),label,flush=True)
with tempfile.TemporaryDirectory(prefix='hs bundle space ') as temp:
    d=Path(temp);bindir=d/'utilities';bindir.mkdir()
    for name in ['uname','dirname','sha256sum','mktemp','rm','mkdir','cp','chmod','mv','cmp','find']:
        (bindir/name).symlink_to(shutil.which(name))
    env=dict(os.environ,PATH=str(bindir));env.pop('HSPATH',None);env.pop('HSROOT',None)
    r=subprocess.run(['/bin/sh',str(ROOT/'scripts/install-native.sh')],env=env,capture_output=True,text=True,timeout=10)
    check(r.returncode==2 and 'usage:' in r.stderr,'installer requires explicit destination')
    r=subprocess.run(['/bin/sh',str(ROOT/'scripts/install-native.sh'),str(d/'absent'/'install')],env=env,capture_output=True,text=True,timeout=10)
    check(r.returncode!=0 and not (d/'absent').exists(),'missing parent does not create or change directories')
    # A second-driver build failure must not publish a partial installation.
    broken=d/'broken checkout'
    broken.mkdir()
    for name in ('scripts','bootstrap','selfhost','runtime','std','docs'):
        shutil.copytree(ROOT/name,broken/name)
    shutil.copyfile(ROOT/'VERSION',broken/'VERSION')
    (broken/'selfhost/be/irinterp_run.holy').write_text('def broken(:\n')
    failed_install=d/'failed install'
    r=subprocess.run(['/bin/sh',str(broken/'scripts/install-native.sh'),str(failed_install)],env=env,capture_output=True,text=True,timeout=240)
    check(r.returncode!=0 and not failed_install.exists() and not list(d.glob('.holyshit-bundle.*')),'interpreter build failure cleans staging without publishing')
    # The third build must also fail without publishing the first two drivers.
    shutil.copyfile(ROOT/'selfhost/be/irinterp_run.holy',broken/'selfhost/be/irinterp_run.holy')
    (broken/'selfhost/fmt.holy').write_text('def broken(:\n')
    failed_fmt_install=d/'failed formatter install'
    r=subprocess.run(['/bin/sh',str(broken/'scripts/install-native.sh'),str(failed_fmt_install)],env=env,capture_output=True,text=True,timeout=240)
    check(r.returncode!=0 and not failed_fmt_install.exists() and not list(d.glob('.holyshit-bundle.*')),'formatter build failure cleans staging without publishing')
    # The fourth build must also fail without publishing the first three drivers.
    shutil.copyfile(ROOT/'selfhost/fmt.holy',broken/'selfhost/fmt.holy')
    (broken/'selfhost/check_run.holy').write_text('def broken(:\n')
    failed_check_install=d/'failed checker install'
    r=subprocess.run(['/bin/sh',str(broken/'scripts/install-native.sh'),str(failed_check_install)],env=env,capture_output=True,text=True,timeout=240)
    check(r.returncode!=0 and not failed_check_install.exists() and not list(d.glob('.holyshit-bundle.*')),'checker build failure cleans staging without publishing')
    # The fifth build must also fail without publishing the first four drivers.
    shutil.copyfile(ROOT/'selfhost/check_run.holy',broken/'selfhost/check_run.holy')
    (broken/'selfhost/test_run.holy').write_text('def broken(:\n')
    failed_test_install=d/'failed tester install'
    r=subprocess.run(['/bin/sh',str(broken/'scripts/install-native.sh'),str(failed_test_install)],env=env,capture_output=True,text=True,timeout=240)
    check(r.returncode!=0 and not failed_test_install.exists() and not list(d.glob('.holyshit-bundle.*')),'tester build failure cleans staging without publishing')
    # The sixth build must also fail without publishing the first five drivers.
    shutil.copyfile(ROOT/'selfhost/test_run.holy',broken/'selfhost/test_run.holy')
    (broken/'selfhost/explain_run.holy').write_text('def broken(:\n')
    failed_explain_install=d/'failed explainer install'
    r=subprocess.run(['/bin/sh',str(broken/'scripts/install-native.sh'),str(failed_explain_install)],env=env,capture_output=True,text=True,timeout=240)
    check(r.returncode!=0 and not failed_explain_install.exists() and not list(d.glob('.holyshit-bundle.*')),'explainer build failure cleans staging without publishing')
    # The seventh build must also fail without publishing the first six drivers.
    shutil.copyfile(ROOT/'selfhost/explain_run.holy',broken/'selfhost/explain_run.holy')
    (broken/'selfhost/cc.holy').write_text('def broken(:\n')
    failed_cc_install=d/'failed compiler install'
    r=subprocess.run(['/bin/sh',str(broken/'scripts/install-native.sh'),str(failed_cc_install)],env=env,capture_output=True,text=True,timeout=240)
    check(r.returncode!=0 and not failed_cc_install.exists() and not list(d.glob('.holyshit-bundle.*')),'compiler build failure cleans staging without publishing')
    # The eighth build must also fail without publishing the first seven drivers.
    shutil.copyfile(ROOT/'selfhost/cc.holy',broken/'selfhost/cc.holy')
    (broken/'selfhost/ir_run.holy').write_text('def broken(:\n')
    failed_ir_install=d/'failed IR dumper install'
    r=subprocess.run(['/bin/sh',str(broken/'scripts/install-native.sh'),str(failed_ir_install)],env=env,capture_output=True,text=True,timeout=240)
    check(r.returncode!=0 and not failed_ir_install.exists() and not list(d.glob('.holyshit-bundle.*')),'IR dumper build failure cleans staging without publishing')
    original=d/'original';moved=d/'moved bundle'
    started=time.monotonic()
    r=subprocess.run(['/bin/sh',str(ROOT/'scripts/install-native.sh'),str(original)],env=env,capture_output=True,text=True,timeout=240)
    print('METRIC candidate_install_wall_seconds',round(time.monotonic()-started,3),flush=True)
    check(r.returncode==0,'build '+r.stderr[-150:])
    if r.returncode:sys.exit(1)
    original.rename(moved)
    launcher=moved/'bin/hs';compiler=moved/'bootstrap/hs-hosted-x86_64'
    r=subprocess.run(['/bin/sh',str(launcher),'repl','input.holy'],env=env,capture_output=True,text=True,timeout=10)
    check(r.returncode==2 and 'unknown command' in r.stderr,'unsupported development command is explicit, no fallback')
    source=d/'main file.holy';module=d/'support.holy';module.write_text('value = 19\n')
    source.write_text('import support\nprint support.value\nprint json_str([1, "ok"])\nprint argv()\nextern:\n  I64 printf(Str format, ..., I64 n)\nprintf("value=%lld\\n", 27)\n')
    expected='19\n[1, "ok"]\n[hello world, $5]\nvalue=27\n'
    # Keep PATH isolated and all sources outside both bundle and checkout.
    r=subprocess.run(['/bin/sh',str(launcher),'run',source.name,'hello world','$5'],cwd=d,env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout==expected,'relocated eager JSON/import/argv/variadic '+repr((r.returncode,r.stdout,r.stderr[-150:])))
    exe=d/'program'
    r=subprocess.run(['/bin/sh',str(launcher),'build',source.name,str(exe)],cwd=d,env=env,capture_output=True,text=True,timeout=60)
    if r.returncode==0:r=subprocess.run([str(exe),'hello world','$5'],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout==expected,'relocated AOT '+repr((r.returncode,r.stdout,r.stderr[-150:])))
    local=dict(env,HSROOT=str(moved),HSPATH=str(moved/'selfhost')+':'+str(moved/'selfhost/be'))
    stage=d/'stage2'
    if '--skip-selfcompile' not in sys.argv:
        r=subprocess.run([str(compiler),str(moved/'selfhost/be/compile.holy'),str(stage)],env=local,capture_output=True,text=True,timeout=180)
        check(r.returncode==0 and stage.read_bytes()==compiler.read_bytes(),'relocated compiler self-compilation')
    # Explicit interpreter: moved bundle, no Python/gcc, no launch-time build.
    interp=moved/'bin/hs-interp'
    print('METRIC installed_interpreter_bytes',interp.stat().st_size,flush=True)
    interp_before=interp.read_bytes()
    interp_mtime=interp.stat().st_mtime_ns
    env['HS_BUNDLE_INTERP']='installed'
    r=subprocess.run(['/bin/sh',str(launcher),'interpret'],env=env,capture_output=True,text=True,timeout=10)
    check(r.returncode==2 and 'usage:' in r.stderr,'interpret requires source')
    source.write_text('import support\nprint support.value\nprint argv()\nprint env("HS_BUNDLE_INTERP")\ntry:\n  raise "caught"\nexcept:\n  print json_str([1, "ok"])\n')
    r=subprocess.run(['/bin/sh',str(launcher),'interpret',source.name,'hello world','$5'],cwd=d,env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and not r.stderr and r.stdout=='19\n[hello world, $5]\ninstalled\n[1, "ok"]\n','relocated explicit interpreter args/import/env/JSON/try '+repr((r.returncode,r.stdout,r.stderr[-150:])))
    check(interp.stat().st_mtime_ns==interp_mtime and interp.read_bytes()==interp_before,'interpret does not rebuild installed driver')
    source.write_text('print "before"\nprint 1 / 0\n')
    r=subprocess.run(['/bin/sh',str(launcher),'interpret',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and r.stdout=='before\n' and 'division by zero' in r.stderr,'interpret runtime failure preserves output and status')
    r=subprocess.run(['/bin/sh',str(launcher),'interpret',str(d/'absent.holy')],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'error:' in r.stderr,'interpret missing source failure')
    source.write_text('def broken(:\n')
    r=subprocess.run(['/bin/sh',str(launcher),'interpret',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'error:' in r.stderr,'interpret parse failure')
    for label,text in [('unsafe','unsafe:\n  Ptr p = alloc(8)\n'),('ffi','extern:\n  I64 puts(Str s)\nputs("must not run")\n')]:
        source.write_text('print "TARGET RAN"\n'+text)
        r=subprocess.run(['/bin/sh',str(launcher),'interpret',str(source)],env=env,capture_output=True,text=True,timeout=30)
        check(r.returncode==3 and not r.stdout and 'irinterp: unsupported' in r.stderr,'interpret '+label+' refused before effects')
    module.write_text('print "MODULE RAN"\nunsafe:\n  Ptr p = alloc(8)\n')
    source.write_text('print "TARGET RAN"\nimport support\n')
    r=subprocess.run(['/bin/sh',str(launcher),'interpret',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==3 and not r.stdout and 'irinterp: unsupported' in r.stderr,'interpret import graph refused before effects')
    module.write_text('value = 19\n')
    interp.write_bytes(interp_before+b'changed')
    source.write_text('print "TARGET RAN"\n')
    r=subprocess.run(['/bin/sh',str(launcher),'interpret',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode!=0 and not r.stdout,'corrupt interpreter refused before target execution')
    # Corrupting this optional execution route must not change run/build.
    source.write_text('print 23\n')
    r=subprocess.run(['/bin/sh',str(launcher),'run',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout=='23\n','run independent of interpreter checksum')
    r=subprocess.run(['/bin/sh',str(launcher),'build',str(source),str(exe)],env=env,capture_output=True,text=True,timeout=60)
    if r.returncode==0:r=subprocess.run([str(exe)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout=='23\n','build independent of interpreter checksum')
    interp.write_bytes(interp_before)
    sums=moved/'INTERP_SHA256SUMS'
    saved_sums=sums.read_bytes()
    sums.unlink()
    r=subprocess.run(['/bin/sh',str(launcher),'interpret',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'install a new complete bundle' in r.stderr,'missing interpreter manifest reports incomplete bundle')
    sums.write_bytes(saved_sums)
    interp.unlink()
    r=subprocess.run(['/bin/sh',str(launcher),'interpret',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'install a new complete bundle' in r.stderr,'missing interpreter binary reports incomplete bundle')
    interp.write_bytes(interp_before)
    interp.chmod(0o755)
    r=subprocess.run(['/bin/sh',str(launcher),'interpret',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout=='23\n','restored interpreter works')
    # Installed formatter is stdout-only and always uses existing comment mode.
    formatter=moved/'bin/hs-fmt'
    formatter_bytes=formatter.read_bytes();formatter_mtime=formatter.stat().st_mtime_ns
    print('METRIC installed_formatter_bytes',len(formatter_bytes),flush=True)
    cases=[('format file.txt','# ไทย header\nx=1 # tail\nprint x\n'),
           ('-dash-name','# comment only\n'),('empty',''),
           ('quirks','class A: # cls\n  # method\n  def f(self): # meth\n    return 1 # ret\nprint 0\n')]
    for name,text in cases:
        path=d/name;path.write_bytes(text.encode())
        reference_interp.reset_parse_state()
        expected_fmt=fmt.fmt_program_c(reference_interp.parse_program(text,raw=True),text)
        r=subprocess.run(['/bin/sh',str(launcher),'fmt',path.name],cwd=d,env=env,capture_output=True,text=True,timeout=30)
        check(r.returncode==0 and not r.stderr and r.stdout==expected_fmt,'relocated fmt exact comments '+name)
        check(path.read_bytes()==text.encode(),'fmt source unchanged '+name)
    check(formatter.read_bytes()==formatter_bytes and formatter.stat().st_mtime_ns==formatter_mtime,'fmt does not rebuild installed driver')
    r=subprocess.run(['/bin/sh',str(launcher),'fmt'],env=env,capture_output=True,text=True,timeout=10)
    check(r.returncode==2 and not r.stdout and 'usage:' in r.stderr,'fmt requires source')
    for extra in ['-w','--check','--comments','second.holy']:
        r=subprocess.run(['/bin/sh',str(launcher),'fmt',str(path),extra],env=env,capture_output=True,text=True,timeout=10)
        check(r.returncode==2 and not r.stdout and 'usage: hs fmt SOURCE' in r.stderr,'fmt refuses extra '+extra)
    # Compare failures to the unchanged bundled source formatter, not Python CLI.
    for label,path in [('parse',d/'bad format.holy'),('missing',d/'missing format.holy')]:
        if label=='parse':path.write_text('def broken(:\n')
        direct=subprocess.run([str(formatter),str(path),'--comments'],env=env,capture_output=True,text=True,timeout=30)
        r=subprocess.run(['/bin/sh',str(launcher),'fmt',str(path)],env=env,capture_output=True,text=True,timeout=30)
        check(r.returncode==1 and (r.returncode,r.stdout,r.stderr)==(direct.returncode,direct.stdout,direct.stderr),'fmt '+label+' failure preserves driver streams/status')
    source.write_text('print "TARGET MUST NOT RUN" # comment\n')
    formatter.write_bytes(formatter_bytes+b'changed')
    r=subprocess.run(['/bin/sh',str(launcher),'fmt',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'formatter checksum failed' in r.stderr,'corrupt formatter refused before output')
    source.write_text('print 31\n')
    for command in ['run','interpret']:
        r=subprocess.run(['/bin/sh',str(launcher),command,str(source)],env=env,capture_output=True,text=True,timeout=30)
        check(r.returncode==0 and r.stdout=='31\n',command+' independent of formatter checksum')
    r=subprocess.run(['/bin/sh',str(launcher),'build',str(source),str(exe)],env=env,capture_output=True,text=True,timeout=60)
    if r.returncode==0:r=subprocess.run([str(exe)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout=='31\n','build independent of formatter checksum')
    formatter.write_bytes(formatter_bytes)
    sums=moved/'FMT_SHA256SUMS';saved_fmt_sums=sums.read_bytes();sums.unlink()
    r=subprocess.run(['/bin/sh',str(launcher),'fmt',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'install a new complete bundle' in r.stderr,'missing formatter manifest reports incomplete bundle')
    sums.write_bytes(saved_fmt_sums);formatter.unlink()
    r=subprocess.run(['/bin/sh',str(launcher),'fmt',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'install a new complete bundle' in r.stderr,'missing formatter binary reports incomplete bundle')
    formatter.write_bytes(formatter_bytes);formatter.chmod(0o755)
    source.write_text('print "TARGET MUST NOT RUN" # comment\n')
    r=subprocess.run(['/bin/sh',str(launcher),'fmt',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and not r.stderr and r.stdout=='print "TARGET MUST NOT RUN"  # comment\n','restored formatter formats without running target')
    # Installed checker scans the source and reachable imports without running them.
    checker=moved/'bin/hs-check'
    checker_bytes=checker.read_bytes();checker_mtime=checker.stat().st_mtime_ns
    print('METRIC installed_checker_bytes',len(checker_bytes),flush=True)
    source.write_text('import support\nprint support.value\nprint missing_name\n')
    r=subprocess.run(['/bin/sh',str(launcher),'check',source.name],cwd=d,env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and not r.stderr and r.stdout=='ok: '+source.name+'\n','relocated check accepts valid source, echoing the path as given like the Python CLI '+repr((r.returncode,r.stdout,r.stderr[-150:])))
    check(checker.read_bytes()==checker_bytes and checker.stat().st_mtime_ns==checker_mtime,'check does not rebuild installed driver')
    r=subprocess.run(['/bin/sh',str(launcher),'check',source.name,'ignored-extra.holy'],cwd=d,env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout=='ok: '+source.name+'\n','check ignores extra positional arguments like the Python CLI')
    source.write_text('import absent_zz\n')
    r=subprocess.run(['/bin/sh',str(launcher),'check',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and r.stderr=="error: cannot find module 'absent_zz' at line 1\n",'check error text matches Python CLI '+repr((r.returncode,r.stdout,r.stderr[-150:])))
    r=subprocess.run(['/bin/sh',str(launcher),'--json','check',str(source)],env=env,capture_output=True,text=True,timeout=30)
    cat_row=[ln for ln in (ROOT/'docs/errors.md').read_text(encoding='utf-8').split('\n') if ln.startswith('| `E012` |')][0]
    cat_hint=cat_row.split(' | ')[3][:-2]
    check(r.returncode==1 and not r.stdout and json.loads(r.stderr)=={'file':str(source),'line':1,'message':"cannot find module 'absent_zz'",'code':'E012','hint':cat_hint},'check --json matches Python CLI shape incl. catalog code/hint '+repr((r.returncode,r.stdout,r.stderr[-150:])))
    r=subprocess.run(['/bin/sh',str(launcher),'check','--json',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and json.loads(r.stderr)['line']==1,'check accepts --json after the command')
    r=subprocess.run(['/bin/sh',str(launcher),'check'],env=env,capture_output=True,text=True,timeout=10)
    check(r.returncode==2 and not r.stdout and 'usage:' in r.stderr,'check requires source')
    source.write_text('print "TARGET MUST NOT RUN"\nwrite_text("EFFECT_MARK","x")\nsystem("touch EFFECT_MARK2")\n')
    r=subprocess.run(['/bin/sh',str(launcher),'check',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout=='ok: '+str(source)+'\n' and not (d/'EFFECT_MARK').exists() and not (d/'EFFECT_MARK2').exists(),'check scans without target effects '+repr((r.returncode,r.stdout,r.stderr[-150:])))
    checker.write_bytes(checker_bytes+b'changed')
    r=subprocess.run(['/bin/sh',str(launcher),'check',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'checker checksum failed' in r.stderr,'corrupt checker refused before scanning')
    # Corrupting this optional analysis route must not change run/interpret/fmt/build.
    source.write_text('print 41\n')
    for command in ['run','interpret']:
        r=subprocess.run(['/bin/sh',str(launcher),command,str(source)],env=env,capture_output=True,text=True,timeout=30)
        check(r.returncode==0 and r.stdout=='41\n',command+' independent of checker checksum')
    r=subprocess.run(['/bin/sh',str(launcher),'fmt',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout=='print 41\n','fmt independent of checker checksum')
    r=subprocess.run(['/bin/sh',str(launcher),'build',str(source),str(exe)],env=env,capture_output=True,text=True,timeout=60)
    if r.returncode==0:r=subprocess.run([str(exe)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and r.stdout=='41\n','build independent of checker checksum')
    checker.write_bytes(checker_bytes)
    sums=moved/'CHECK_SHA256SUMS';saved_check_sums=sums.read_bytes();sums.unlink()
    r=subprocess.run(['/bin/sh',str(launcher),'check',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'install a new complete bundle' in r.stderr,'missing checker manifest reports incomplete bundle')
    sums.write_bytes(saved_check_sums);checker.unlink()
    r=subprocess.run(['/bin/sh',str(launcher),'check',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==1 and not r.stdout and 'install a new complete bundle' in r.stderr,'missing checker binary reports incomplete bundle')
    checker.write_bytes(checker_bytes);checker.chmod(0o755)
    r=subprocess.run(['/bin/sh',str(launcher),'check',str(source)],env=env,capture_output=True,text=True,timeout=30)
    check(r.returncode==0 and not r.stderr and r.stdout=='ok: '+str(source)+'\n','restored checker scans without running target')
    # Installed tester runs def test_* functions on the installed interpreter.
    tester=moved/'bin/hs-test'
    tester_bytes=tester.read_bytes();tester_mtime=tester.stat().st_mtime_ns
    print('METRIC installed_tester_bytes',len(tester_bytes),flush=True)
    tsource=d/'sample tests.holy'
    tsource.write_text('def test_ok():\n  assert 1 + 1 == 2\n\ndef test_bad():\n  raise "boom"\n')
    r=subprocess.run(['/bin/sh',str(launcher),'test',str(tsource)],env=env,capture_output=True,text=True,timeout=60)
    check(r.returncode==1 and not r.stderr and r.stdout=='ok   '+str(tsource)+'::test_ok\nFAIL '+str(tsource)+'::test_bad: boom at line 5\n1 passed, 1 failed\n','relocated test reports pass/fail like the Python CLI '+repr((r.returncode,r.stdout,r.stderr[-150:])))
    check(tester.read_bytes()==tester_bytes and tester.stat().st_mtime_ns==tester_mtime,'test does not rebuild installed driver')
    tsource.write_text('def test_ok():\n  assert 1 + 1 == 2\n')
    r=subprocess.run(['/bin/sh',str(launcher),'test',str(tsource),'--json'],env=env,capture_output=True,text=True,timeout=60)
    check(r.returncode==0 and not r.stderr and json.loads(r.stdout)=={'passed':1,'failed':0,'results':[{'file':str(tsource),'test':'test_ok','ok':True}]},'test --json matches Python CLI shape '+repr((r.returncode,r.stdout,r.stderr[-150:])))
