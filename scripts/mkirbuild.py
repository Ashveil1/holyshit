#!/usr/bin/env python3
"""Regenerate the hs AST-to-IR builder from the Python semantic reference.
_n/_t keyword records are flattened before the restricted translation.
"""
import ast
import pathlib
import re
import sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from py2hs import translate
root = pathlib.Path(__file__).resolve().parent.parent
mod = ast.parse((root / 'ir.py').read_text())
class Records(ast.NodeTransformer):
    def visit_Call(self, n):
        self.generic_visit(n)
        if isinstance(n.func, ast.Name) and n.func.id in ('_n', '_t'):
            n.args.append(ast.Dict(keys=[ast.Constant(k.arg) for k in n.keywords], values=[k.value for k in n.keywords]))
            n.keywords = []
        if isinstance(n.func, ast.Name) and n.func.id == '_FuncBuild':
            if n.keywords:
                n.args.extend(k.value for k in n.keywords)
                n.keywords = []
        return n
items = [n for n in mod.body if isinstance(n, (ast.ClassDef, ast.FunctionDef)) and 69 <= n.lineno < 831]
items = Records().visit(ast.Module(body=items, type_ignores=[]))
ast.fix_missing_locations(items)
path = pathlib.Path('/tmp/irbuild-source.py')
src = ast.unparse(items).replace('id(fbody)', 'id(entry)')
path.write_text(src)
errs = translate([str(path)], '/tmp/irbuild-raw.hs', str(root / 'x64.py'))
if errs:
    raise SystemExit('\n'.join(errs))
s = pathlib.Path('/tmp/irbuild-raw.hs').read_text()
s = re.sub(r'\bpy_(\w+)\(', r'pyrt.py_\1(', s)
s = s.replace('interp.BUILTINS', 'parselib.BUILTINS')
s = s.replace('pyrt.py_update(fb.gnames, s["names"])', 'pyrt.py_extend_set(fb.gnames, s["names"])')
s = s.replace('not (pyrt.py_id(entry) in fb.finactive)', 'not pyrt.py_get(fb.finactive, pyrt.py_id(entry), false)')
header = '''# AST -> flat CFG, differential against ir.py. Generated by scripts/mkirbuild.py.
import pyrt
import parselib
import iropt

def _n(kind, line, kw):
  kw["op"] = kind
  kw["line"] = line
  return kw

def _t(kind, line, kw):
  kw["term"] = kind
  kw["line"] = line
  return kw

'''
footer = '''
def build_module(prog, pfx):
  b = Builder(pfx)
  m = b.build(prog, pfx)
  iropt.optimize_module(m)
  return m
'''
(root / 'selfhost/be/irbuild.hs').write_text(header+s+footer)
import subprocess
subprocess.run([sys.executable, str(root/'hs.py'), 'fmt', str(root/'selfhost/be/irbuild.hs'), '-w'], check=True)
