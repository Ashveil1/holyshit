#!/usr/bin/env python3
"""Regenerate selfhost/lspdata.holy from scripts/lang_data.py.

    python3 scripts/gen_lspdata.py          # write selfhost/lspdata.holy
    python3 scripts/gen_lspdata.py --check  # exit 1 when stale

The native language server (selfhost/lsp.holy) needs the same keyword and
builtin tables lsp.py reads; keep one source of truth in lang_data.py.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from scripts import lang_data  # noqa: E402

OUT = os.path.join(ROOT, "selfhost", "lspdata.holy")


def esc(s):
    # hs string escapes: only \n \t \r \" \\ \0
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r"))


def render():
    lines = [
        "# GENERATED by scripts/gen_lspdata.py from scripts/lang_data.py.",
        "# Do not edit by hand; run the generator after changing lang_data.py.",
        "",
        "KEYWORDS = {}",
    ]
    for word in sorted(lang_data.KEYWORDS):
        lines.append('KEYWORDS["%s"] = "%s"'
                     % (esc(word), esc(lang_data.KEYWORDS[word])))
    lines.append("KEYWORD_NAMES = [%s]"
                 % ", ".join('"%s"' % esc(w)
                             for w in sorted(lang_data.KEYWORDS)))
    lines.append("")
    lines.append("# name -> [signature, description, [supported backends sorted]]")
    lines.append("BUILTINS = {}")
    for name in sorted(lang_data.BUILTINS):
        sig, desc, be = lang_data.BUILTINS[name]
        bes = ", ".join('"%s"' % esc(b) for b in sorted(be))
        lines.append('BUILTINS["%s"] = ["%s", "%s", [%s]]'
                     % (esc(name), esc(sig), esc(desc), bes))
    lines.append("BUILTIN_NAMES = [%s]"
                 % ", ".join('"%s"' % esc(n)
                             for n in sorted(lang_data.BUILTINS)))
    lines.append("")
    return "\n".join(lines)


def main():
    want = render()
    if "--check" in sys.argv:
        cur = ""
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8") as f:
                cur = f.read()
        if cur != want:
            print("selfhost/lspdata.holy is stale: run scripts/gen_lspdata.py")
            sys.exit(1)
        print("selfhost/lspdata.holy up to date")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(want)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
