#!/usr/bin/env python3
"""Generate machine-readable docs from canonical sources.

    python3 scripts/gen_api.py   # writes docs/api.json + docs/builtins.md

Sources: scripts/lang_data.py (signatures/descriptions/support),
interp.BUILTINS (runtime authority — every key must be covered).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import interp
import lang_data


def main():
    missing = set(interp.BUILTINS) - set(lang_data.BUILTINS)
    extra = set(lang_data.BUILTINS) - set(interp.BUILTINS) - {"pmm_total",
                                                              "pmm_free"}
    if missing or extra:
        print(f"lang_data drift: missing={sorted(missing)} "
              f"extra={sorted(extra)}", file=sys.stderr)
        return 1
    api = {
        "language": "holyshit",
        "version": open(os.path.join(ROOT, "VERSION")).read().strip(),
        "keywords": lang_data.KEYWORDS,
        "builtins": {
            name: {"sig": sig, "desc": desc, "backends": sorted(be)}
            for name, (sig, desc, be) in lang_data.BUILTINS.items()
        },
    }
    docs = os.path.join(ROOT, "docs")
    os.makedirs(docs, exist_ok=True)
    with open(os.path.join(docs, "api.json"), "w",
              encoding="utf-8") as f:
        json.dump(api, f, indent=1, ensure_ascii=False)
        f.write("\n")
    lines = ["# Builtins (generated — do not edit by hand)",
             "",
             "> Generated by `scripts/gen_api.py` from `scripts/lang_data.py`.",
             "> Column ✓ = supported. `unsafe` builtins work inside `unsafe:` only.",
             "",
             "| builtin | signature | interp | native | xbuild | xkernel |",
             "|---|---|---|---|---|---|"]
    for name in sorted(lang_data.BUILTINS):
        sig, desc, be = lang_data.BUILTINS[name]
        cols = ["✓" if b in be else " " for b in
                ("interp", "native", "xbuild", "xkernel")]
        lines.append(f"| `{name}` | `{sig}` | {' | '.join(cols)} |")
        lines.append(f"| | {desc} |||||")
    lines += ["",
              "Full descriptions live in `docs/api.json` "
              "(same source, machine-readable)."]
    with open(os.path.join(docs, "builtins.md"), "w",
              encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote docs/api.json + docs/builtins.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
